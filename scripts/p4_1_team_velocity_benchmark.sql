SET NOCOUNT ON;

/*
P4.1 - Team velocity benchmark (SWAG vs Velocity)

Purpose:
- Validate velocity model behavior for a specific Program/Team benchmark scope.
- Compare Derived FTE totals by PI:
  * SWAG path (DERIVED_FTE_FEATURE)
  * Velocity path recalculated from snapshot:
      SWAG_POINTS / EFFECTIVE_BASELINE_POINTS

Inputs:
  @year_from / @year_to
  @program_name / @team_name
*/

DECLARE @year_from INT = 2025;
DECLARE @year_to INT = 2025;
DECLARE @program_name NVARCHAR(200) = N'R&M';
DECLARE @team_name NVARCHAR(200) = N'ERNE WEST';
DECLARE @program_name_resolved NVARCHAR(200) = @program_name;
DECLARE @team_name_resolved NVARCHAR(200) = @team_name;
DECLARE @program_id_resolved NVARCHAR(200) = NULL;
DECLARE @team_id_resolved NVARCHAR(200) = NULL;

;WITH p_pick AS (
  SELECT TOP (1)
    NULLIF(LTRIM(RTRIM(p.PROGRAMID)), '') AS PROGRAMID_CANONICAL,
    NULLIF(LTRIM(RTRIM(p.PROGRAMNAME)), '') AS PROGRAMNAME_CANONICAL
  FROM PROGRAMS p
  WHERE UPPER(LTRIM(RTRIM(COALESCE(p.PROGRAMNAME, '')))) = UPPER(LTRIM(RTRIM(@program_name)))
     OR UPPER(LTRIM(RTRIM(COALESCE(p.PROGRAM_DISPLAY_NAME, '')))) = UPPER(LTRIM(RTRIM(@program_name)))
  ORDER BY
    CASE
      WHEN UPPER(LTRIM(RTRIM(COALESCE(p.PROGRAM_DISPLAY_NAME, '')))) = UPPER(LTRIM(RTRIM(@program_name))) THEN 0
      WHEN UPPER(LTRIM(RTRIM(COALESCE(p.PROGRAMNAME, '')))) = UPPER(LTRIM(RTRIM(@program_name))) THEN 1
      ELSE 2
    END
),
t_pick AS (
  SELECT TOP (1)
    NULLIF(LTRIM(RTRIM(t.TEAMID)), '') AS TEAMID_CANONICAL,
    NULLIF(LTRIM(RTRIM(t.TEAMNAME)), '') AS TEAMNAME_CANONICAL
  FROM TEAMS t
  WHERE UPPER(LTRIM(RTRIM(COALESCE(t.TEAMNAME, '')))) = UPPER(LTRIM(RTRIM(@team_name)))
     OR UPPER(LTRIM(RTRIM(COALESCE(t.TEAM_DISPLAY_NAME, '')))) = UPPER(LTRIM(RTRIM(@team_name)))
  ORDER BY
    CASE
      WHEN UPPER(LTRIM(RTRIM(COALESCE(t.TEAM_DISPLAY_NAME, '')))) = UPPER(LTRIM(RTRIM(@team_name))) THEN 0
      WHEN UPPER(LTRIM(RTRIM(COALESCE(t.TEAMNAME, '')))) = UPPER(LTRIM(RTRIM(@team_name))) THEN 1
      ELSE 2
    END
)
SELECT
  @program_id_resolved = (SELECT PROGRAMID_CANONICAL FROM p_pick),
  @program_name_resolved = COALESCE((SELECT PROGRAMNAME_CANONICAL FROM p_pick), @program_name),
  @team_id_resolved = (SELECT TEAMID_CANONICAL FROM t_pick),
  @team_name_resolved = COALESCE((SELECT TEAMNAME_CANONICAL FROM t_pick), @team_name);

DECLARE @global_baseline_points FLOAT =
  COALESCE(
    (
      SELECT TOP (1) TRY_CONVERT(FLOAT, JSON_VALUE(ap.CONFIG_JSON, '$.swag.points_per_fte'))
      FROM ADO_PROFILES ap
      WHERE COALESCE(ap.IS_ACTIVE, 0) = 1
      ORDER BY ap.UPDATED_AT DESC
    ),
    (
      SELECT TOP (1) TRY_CONVERT(FLOAT, JSON_VALUE(ap.CONFIG_JSON, '$.swag.points_per_fte'))
      FROM ADO_PROFILES ap
      ORDER BY ap.UPDATED_AT DESC
    ),
    65.0
  );

IF OBJECT_ID('tempdb..#scope_features') IS NOT NULL
  DROP TABLE #scope_features;

IF OBJECT_ID('tempdb..#scope_joined') IS NOT NULL
  DROP TABLE #scope_joined;

SELECT
  d.FEATURE_ID,
  COALESCE(NULLIF(LTRIM(RTRIM(d.TEAMID)), ''), 'UNKNOWN') AS TEAMID,
  UPPER(LTRIM(RTRIM(COALESCE(d.TEAMNAME, '')))) AS TEAM_U,
  UPPER(LTRIM(RTRIM(COALESCE(d.PROGRAMNAME, '')))) AS PROGRAM_U,
  d.PROGRAMNAME,
  d.TEAMNAME,
  TRY_CONVERT(INT, d.YEAR) AS YEAR_I,
  TRY_CONVERT(INT, d.PI) AS PI_I,
  COALESCE(NULLIF(LTRIM(RTRIM(d.PI_LABEL)), ''), CONCAT(TRY_CONVERT(INT, d.YEAR), ' I', TRY_CONVERT(INT, d.PI))) AS PI_LABEL,
  TRY_CONVERT(FLOAT, d.SWAG_POINTS) AS SWAG_POINTS,
  TRY_CONVERT(FLOAT, d.DERIVED_FTE_FEATURE) AS DERIVED_FTE_SWAG,
  TRY_CONVERT(FLOAT, d.DERIVED_FTE_FEATURE_VELOCITY) AS DERIVED_FTE_VELOCITY_VIEW,
  COALESCE(TRY_CONVERT(INT, d.IS_MSP_FEATURE), 0) AS IS_MSP_FEATURE
INTO #scope_features
FROM VW_TCO_FEATURE_DEMAND d
WHERE TRY_CONVERT(INT, d.YEAR) BETWEEN @year_from AND @year_to
  AND TRY_CONVERT(INT, d.PI) IS NOT NULL
  AND COALESCE(d.IN_SCOPE_FOR_ROADMAP, 0) = 1
  AND COALESCE(TRY_CONVERT(INT, d.IS_MSP_FEATURE), 0) = 0
  AND (
    (@program_id_resolved IS NOT NULL AND UPPER(LTRIM(RTRIM(COALESCE(d.PROGRAMID, '')))) = UPPER(LTRIM(RTRIM(@program_id_resolved))))
    OR (@program_id_resolved IS NULL AND UPPER(LTRIM(RTRIM(COALESCE(d.PROGRAMNAME, '')))) = UPPER(LTRIM(RTRIM(@program_name_resolved))))
  )
  AND (
    (@team_id_resolved IS NOT NULL AND UPPER(LTRIM(RTRIM(COALESCE(d.TEAMID, '')))) = UPPER(LTRIM(RTRIM(@team_id_resolved)))
    )
    OR (@team_id_resolved IS NULL AND UPPER(LTRIM(RTRIM(COALESCE(d.TEAMNAME, '')))) = UPPER(LTRIM(RTRIM(@team_name_resolved))))
  );

SELECT
  sf.*,
  TRY_CONVERT(FLOAT, sv.EFFECTIVE_BASELINE_POINTS) AS SNAPSHOT_BASELINE_POINTS,
  UPPER(COALESCE(sv.BASELINE_SOURCE, 'GLOBAL')) AS SNAPSHOT_BASELINE_SOURCE,
  CAST(
    CASE
      WHEN COALESCE(TRY_CONVERT(FLOAT, sv.EFFECTIVE_BASELINE_POINTS), 0.0) > 0
        THEN TRY_CONVERT(FLOAT, sv.EFFECTIVE_BASELINE_POINTS)
      ELSE @global_baseline_points
    END AS FLOAT
  ) AS BASELINE_POINTS_USED,
  CAST(
    CASE
      WHEN COALESCE(TRY_CONVERT(FLOAT, sf.SWAG_POINTS), 0.0) <= 0 THEN 0.0
      WHEN COALESCE(TRY_CONVERT(FLOAT, sv.EFFECTIVE_BASELINE_POINTS), 0.0) > 0
        THEN COALESCE(TRY_CONVERT(FLOAT, sf.SWAG_POINTS), 0.0) / NULLIF(TRY_CONVERT(FLOAT, sv.EFFECTIVE_BASELINE_POINTS), 0.0)
      ELSE COALESCE(TRY_CONVERT(FLOAT, sf.SWAG_POINTS), 0.0) / NULLIF(@global_baseline_points, 0.0)
    END AS FLOAT
  ) AS DERIVED_FTE_VELOCITY_CALC
INTO #scope_joined
FROM #scope_features sf
LEFT JOIN TCO_TEAM_VELOCITY_SNAPSHOT sv
  ON COALESCE(NULLIF(LTRIM(RTRIM(sv.TEAMID)), ''), 'UNKNOWN') = sf.TEAMID
 AND TRY_CONVERT(INT, sv.YEAR) = sf.YEAR_I
 AND TRY_CONVERT(INT, sv.PI) = sf.PI_I;

-- Resultset 1: scope overview
SELECT
  @year_from AS YEAR_FROM,
  @year_to AS YEAR_TO,
  @program_name_resolved AS PROGRAM_SCOPE,
  @team_name_resolved AS TEAM_SCOPE,
  CAST(@global_baseline_points AS DECIMAL(18,2)) AS GLOBAL_BASELINE_POINTS,
  COUNT(*) AS FEATURE_ROWS,
  COUNT(DISTINCT FEATURE_ID) AS FEATURES_DISTINCT,
  SUM(CASE WHEN COALESCE(SWAG_POINTS, 0) > 0 THEN 1 ELSE 0 END) AS SWAG_READY_ROWS,
  SUM(CASE WHEN COALESCE(SNAPSHOT_BASELINE_POINTS, 0) > 0 THEN 1 ELSE 0 END) AS ROWS_WITH_SNAPSHOT_BASELINE,
  SUM(CASE WHEN COALESCE(SNAPSHOT_BASELINE_POINTS, 0) <= 0 THEN 1 ELSE 0 END) AS ROWS_WITH_GLOBAL_FALLBACK,
  CAST(SUM(COALESCE(DERIVED_FTE_SWAG, 0.0)) AS DECIMAL(18,2)) AS DERIVED_FTE_SWAG_TOTAL,
  CAST(SUM(COALESCE(DERIVED_FTE_VELOCITY_CALC, 0.0)) AS DECIMAL(18,2)) AS DERIVED_FTE_VELOCITY_CALC_TOTAL,
  CAST(SUM(COALESCE(DERIVED_FTE_VELOCITY_VIEW, 0.0)) AS DECIMAL(18,2)) AS DERIVED_FTE_VELOCITY_VIEW_TOTAL,
  CAST(
    SUM(COALESCE(DERIVED_FTE_VELOCITY_CALC, 0.0))
    - SUM(COALESCE(DERIVED_FTE_SWAG, 0.0))
    AS DECIMAL(18,2)
  ) AS DELTA_VELOCITY_MINUS_SWAG
FROM #scope_joined;

-- Resultset 2: PI-level comparison
SELECT
  YEAR_I AS YEAR,
  PI_I AS PI,
  PI_LABEL,
  COUNT(DISTINCT FEATURE_ID) AS FEATURES_N,
  CAST(SUM(COALESCE(SWAG_POINTS, 0.0)) AS DECIMAL(18,2)) AS SWAG_POINTS_TOTAL,
  CAST(AVG(COALESCE(BASELINE_POINTS_USED, 0.0)) AS DECIMAL(18,2)) AS AVG_BASELINE_POINTS_USED,
  CAST(SUM(COALESCE(DERIVED_FTE_SWAG, 0.0)) AS DECIMAL(18,2)) AS DERIVED_FTE_SWAG_TOTAL,
  CAST(SUM(COALESCE(DERIVED_FTE_VELOCITY_CALC, 0.0)) AS DECIMAL(18,2)) AS DERIVED_FTE_VELOCITY_CALC_TOTAL,
  CAST(
    SUM(COALESCE(DERIVED_FTE_VELOCITY_CALC, 0.0))
    - SUM(COALESCE(DERIVED_FTE_SWAG, 0.0))
    AS DECIMAL(18,2)
  ) AS DELTA_VELOCITY_MINUS_SWAG,
  MAX(SNAPSHOT_BASELINE_SOURCE) AS BASELINE_SOURCE_SAMPLE
FROM #scope_joined
GROUP BY YEAR_I, PI_I, PI_LABEL
ORDER BY YEAR_I, PI_I;

-- Resultset 3: baseline source distribution in this scope
SELECT
  COALESCE(NULLIF(SNAPSHOT_BASELINE_SOURCE, ''), 'GLOBAL') AS SNAPSHOT_BASELINE_SOURCE,
  COUNT(*) AS ROWS_N
FROM #scope_joined
GROUP BY COALESCE(NULLIF(SNAPSHOT_BASELINE_SOURCE, ''), 'GLOBAL')
ORDER BY ROWS_N DESC;

-- Resultset 4: feature-level sample for spot-check
SELECT TOP (50)
  FEATURE_ID,
  YEAR_I AS YEAR,
  PI_I AS PI,
  PI_LABEL,
  CAST(COALESCE(SWAG_POINTS, 0.0) AS DECIMAL(18,2)) AS SWAG_POINTS,
  CAST(COALESCE(BASELINE_POINTS_USED, 0.0) AS DECIMAL(18,2)) AS BASELINE_POINTS_USED,
  CAST(COALESCE(DERIVED_FTE_SWAG, 0.0) AS DECIMAL(18,4)) AS DERIVED_FTE_SWAG,
  CAST(COALESCE(DERIVED_FTE_VELOCITY_CALC, 0.0) AS DECIMAL(18,4)) AS DERIVED_FTE_VELOCITY_CALC,
  CAST(COALESCE(DERIVED_FTE_VELOCITY_VIEW, 0.0) AS DECIMAL(18,4)) AS DERIVED_FTE_VELOCITY_VIEW
FROM #scope_joined
ORDER BY YEAR_I, PI_I, FEATURE_ID;
